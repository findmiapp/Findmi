// Prints the Taxonomy V2 Pass 2 generated SQL (staged Category rows, the V2
// tree, Category → Topic implications, legacy → V2 mappings) from
// src/lib/taxonomy/v2.ts + v2-legacy.ts — the ONE source. The migration
// embeds this output verbatim; tests/taxonomy-v2-pass2.test.mjs fails if
// they drift.
//   node scripts/taxonomy-v2-pass2-sql.mjs
import { createRequire, registerHooks } from "node:module";
import { readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const { transform } = createRequire(import.meta.url)("sucrase");
registerHooks({
  resolve(spec, ctx, next) {
    if (spec.startsWith("./") && ctx.parentURL?.endsWith(".ts")) return { url: pathToFileURL(resolve(dirname(fileURLToPath(ctx.parentURL)), `${spec}.ts`)).href, shortCircuit: true };
    return next(spec, ctx);
  },
  load(url, ctx, next) {
    if (url.endsWith(".ts")) return { format: "module", source: transform(readFileSync(fileURLToPath(url), "utf8"), { transforms: ["typescript"] }).code, shortCircuit: true };
    return next(url, ctx);
  },
});
const T = await import(pathToFileURL(`${ROOT}src/lib/taxonomy/v2.ts`).href);
const L = await import(pathToFileURL(`${ROOT}src/lib/taxonomy/v2-legacy.ts`).href);

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const KINDS = ["event", "business", "location", "product"];
const out = ["-- ================================================================ 6. staged trees + mappings (generated by scripts/taxonomy-v2-pass2-sql.mjs)", ""];

// 6a. New rows → status 'staged' (parent_id stays NULL: structure is category_tree_v2).
out.push("insert into public.categories (name, slug, kind, status, show_on_home) values");
const fresh = KINDS.flatMap((k) => L.v2Nodes(k).filter((x) => !x.reuse).map((x) => `  (${q(x.name)}, ${q(x.slug)}, ${q(k)}, 'staged', false)`));
out.push(fresh.join(",\n"), "on conflict (kind, slug) do nothing;", "");

// 6b. Fail loudly if a slug that should be new already belonged to a V1 row,
// or a reused V1 row is missing / not live.
out.push("do $$", "begin");
for (const k of KINDS)
  for (const x of L.v2Nodes(k)) {
    const want = x.reuse ? "active" : "staged";
    out.push(`  if not exists (select 1 from public.categories where kind = ${q(k)} and slug = ${q(x.slug)} and status = ${q(want)}) then raise exception 'Taxonomy V2: expected % row %/%', ${q(want)}, ${q(k)}, ${q(x.slug)}; end if;`);
  }
out.push("end $$;", "");

// 6c. The V2 tree (parents first), with V2 labels for reused rows.
for (const k of KINDS)
  L.v2Nodes(k).forEach((x, i) => {
    const parent = x.parent ? `(select c2.id from public.categories c2 where c2.kind = ${q(k)} and c2.slug = ${q(x.parent)})` : "null";
    const label = x.name ? `nullif(${q(x.name)}, c.name)` : "null";
    out.push(`insert into public.category_tree_v2 (category_id, kind, parent_category_id, display_name, sort_order) select c.id, ${q(k)}, ${parent}, ${label}, ${(i + 1) * 10} from public.categories c where c.kind = ${q(k)} and c.slug = ${q(x.slug)} on conflict (category_id) do nothing;`);
  });
out.push("");

// 6d. Category → Topic implications.
for (const imp of T.V2_CATEGORY_TOPIC_IMPLICATIONS)
  for (const t of imp.topics)
    out.push(`insert into public.category_topics (category_id, topic_id) select c.id, tp.id from public.categories c join public.category_tree_v2 v on v.category_id = c.id, public.topics tp where c.kind = ${q(imp.kind)} and c.slug = ${q(imp.slug)} and tp.slug = ${q(t)} on conflict do nothing;`);
out.push("");

// 6e. Every V1 classification → V2 (inactive: status stays 'draft').
out.push("insert into public.taxonomy_legacy_mappings (legacy_source, legacy_kind, legacy_slug, targets, mapping_confidence, status, note) values");
out.push(
  L.LEGACY_MAPPINGS.map((x) => `  ('category', ${q(x.kind)}, ${q(x.slug)}, ${q(JSON.stringify(x.targets))}::jsonb, ${q(L.mappingStatus(x))}, 'draft', ${x.note ? q(x.note) : "null"})`).join(",\n"),
  "on conflict (legacy_source, legacy_kind, legacy_slug) do update",
  "  set targets = excluded.targets, mapping_confidence = excluded.mapping_confidence, note = excluded.note, updated_at = now()",
  "  where public.taxonomy_legacy_mappings.status = 'draft';",
  "",
);
process.stdout.write(out.join("\n"));
