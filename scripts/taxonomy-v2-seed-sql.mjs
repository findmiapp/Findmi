// Prints the Taxonomy V2 Pass 1 seed SQL from src/lib/taxonomy/v2.ts — the
// ONE source of the launch vocabulary. The migration embeds this output
// verbatim; tests/taxonomy-v2-foundation.test.mjs fails if they drift.
//   node scripts/taxonomy-v2-seed-sql.mjs
import { createRequire, registerHooks } from "node:module";
import { readFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const { transform } = createRequire(import.meta.url)("sucrase");
registerHooks({
  load(url, ctx, next) {
    if (url.endsWith(".ts")) return { format: "module", source: transform(readFileSync(fileURLToPath(url), "utf8"), { transforms: ["typescript"] }).code, shortCircuit: true };
    return next(url, ctx);
  },
});
const T = await import(pathToFileURL(`${ROOT}src/lib/taxonomy/v2.ts`).href);
process.stdout.write(T_seedSql(T));

export function T_seedSql(T) {
  const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
  const arr = (xs) => (xs && xs.length ? `array[${xs.map(q).join(", ")}]::text[]` : "'{}'::text[]");
  const out = ["-- ================================================================ 11. launch vocabulary (generated by scripts/taxonomy-v2-seed-sql.mjs)", ""];

  out.push("insert into public.taxonomy_terms (vocabulary, slug, name, sort_order, suggests_benefits) values");
  const terms = [];
  for (const vocab of T.TERM_VOCABULARIES) T.TERM_SEEDS[vocab].forEach((t, i) => terms.push(`  (${q(vocab)}, ${q(t.slug)}, ${q(t.name)}, ${(i + 1) * 10}, ${arr(t.suggestsBenefits)})`));
  out.push(terms.join(",\n"), "on conflict (vocabulary, slug) do nothing;", "");

  out.push("insert into public.topics (slug, name, kind, sort_order) values");
  out.push(T.TOPIC_SEEDS.map((t, i) => `  (${q(t.slug)}, ${q(t.name)}, ${q(t.kind)}, ${(i + 1) * 10})`).join(",\n"), "on conflict (slug) do nothing;", "");
  for (const t of T.TOPIC_SEEDS.filter((x) => x.broader))
    out.push(`update public.topics c set broader_topic_id = p.id from public.topics p where c.slug = ${q(t.slug)} and p.slug = ${q(t.broader)} and c.broader_topic_id is null;`);
  out.push("");

  out.push("insert into public.attribute_definitions (key, label, entity_types, value_type, allowed_values, attribute_group, requires_category_scope, sort_order) values");
  out.push(T.ATTRIBUTE_SEEDS.map((d, i) => `  (${q(d.key)}, ${q(d.label)}, ${arr(d.entityTypes)}, ${q(d.valueType)}, ${d.allowedValues ? arr(d.allowedValues) : "null"}, ${q(d.group)}, ${d.requiresCategoryScope}, ${(i + 1) * 10})`).join(",\n"), "on conflict (key) do nothing;", "");

  const ID_TABLE = { topic: "topics", event_type: "taxonomy_terms", experience_mechanic: "taxonomy_terms", appearance_type: "taxonomy_terms", opportunity_category: "taxonomy_terms" };
  const conflict = "on conflict (phrase, dimension, (coalesce(target_id::text, target_code))) do nothing;";
  const codeRows = T.ALIAS_SEEDS.filter((s) => T.ALIAS_CODE_DIMENSIONS.includes(s.dimension));
  out.push("insert into public.taxonomy_aliases (phrase, dimension, target_code, entity_types, source) values");
  out.push(codeRows.map((s) => `  (${q(T.normalizeAliasPhrase(s.phrase))}, ${q(s.dimension)}, ${q(s.target)}, ${s.entityTypes ? arr(s.entityTypes) : "null"}, 'migration')`).join(",\n"), conflict, "");
  for (const s of T.ALIAS_SEEDS.filter((x) => !T.ALIAS_CODE_DIMENSIONS.includes(x.dimension))) {
    const table = ID_TABLE[s.dimension];
    const where = table === "taxonomy_terms" ? `x.vocabulary = ${q(s.dimension)} and x.slug = ${q(s.target)}` : `x.slug = ${q(s.target)}`;
    out.push(`insert into public.taxonomy_aliases (phrase, dimension, target_id, entity_types, source) select ${q(T.normalizeAliasPhrase(s.phrase))}, ${q(s.dimension)}, x.id, ${s.entityTypes ? arr(s.entityTypes) : "null"}, 'migration' from public.${table} x where ${where} ${conflict}`);
  }
  out.push("");

  out.push("insert into public.taxonomy_legacy_mappings (legacy_source, legacy_kind, legacy_slug, targets, status, note) values");
  out.push(T.LEGACY_EVENT_FORMAT_MAPPINGS.map((m) => `  ('category', ${q(m.legacyKind)}, ${q(m.legacySlug)}, ${q(JSON.stringify(m.targets))}::jsonb, 'draft', ${m.note ? q(m.note) : "null"})`).join(",\n"), "on conflict (legacy_source, legacy_kind, legacy_slug) do nothing;", "");
  return out.join("\n");
}
